function dictionaryLocale(locale: string): TranslationLocale {
  if (locale.startsWith('mr')) return 'mr-IN';
  if (locale.startsWith('hi')) return 'hi-IN';
  return 'en-IN';
}

export function translate(locale: string | null | undefined, sourceText: string): string {
  const key = String(sourceText ?? '');
  return dictionaries[dictionaryLocale(locale || 'en-IN')][key] ?? key;
}

export function translatedLocaleCoverage(locale: string | null | undefined): 'translated' | 'english-fallback' {
  const normalized = dictionaryLocale(locale || 'en-IN');
  return normalized === 'mr-IN' || normalized === 'hi-IN' || normalized === 'en-IN'
    ? 'translated'
    : 'english-fallback';
}
